#!/usr/bin/env python3
"""Generate original Q23 windowed-sinc banks for the host SRC design reference.

32 fractional intervals with linear interpolation. The DSP implementation,
coefficient placement and processing budget are not yet qualified.
"""
import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PHASES = 32
CUTOFF = 14500.0
BETA = 8.6


def i0(x):
    term = total = 1.0
    for k in range(1, 80):
        term *= (x / (2 * k)) ** 2
        total += term
        if term < total * 1e-16:
            break
    return total


def bank(rate, taps):
    rows = []
    half = (taps - 1) / 2
    scale = 2 * CUTOFF / rate
    for phase in range(PHASES + 1):
        row = []
        for k in range(taps):
            x = k + phase / PHASES - half
            u = x / half
            window = i0(BETA * math.sqrt(max(0, 1-u*u))) / i0(BETA) if abs(u) <= 1 else 0
            sinc = 1 if x == 0 else math.sin(math.pi * scale * x) / (math.pi * scale * x)
            row.append(scale * sinc * window)
        total = sum(row)
        quant = [round(v / total * (1 << 23)) for v in row]
        # Exact DC normalization at every stored phase, before interpolation.
        quant[max(range(taps), key=lambda i: abs(quant[i]))] += (1 << 23) - sum(quant)
        assert all(-(1 << 23) <= v < (1 << 23) for v in quant)
        rows.append(quant)
    return rows


def source():
    out = ['// Copyright 2026 cscobey. MIT. Generated by generate_src.py.',
           '// Host SRC design reference; not a qualified DSP package.',
           '#pragma once', '#include <cstdint>', 'namespace mist {',
           f'inline constexpr int kSrcPhases = {PHASES};']
    for name, rate, taps in [('Down', 44100, 96), ('Up', 32000, 48)]:
        out.append(f'inline constexpr int32_t kSrc{name}[{(PHASES + 1) * taps}] = {{')
        for row in bank(rate, taps):
            out.append('  ' + ', '.join(map(str, row)) + ',')
        out.append('};')
    out.append('}  // namespace mist')
    return '\n'.join(out) + '\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'src_coefficients.h'
    result = source()
    if args.check:
        if path.read_text() != result:
            raise SystemExit('Stale SRC coefficients; run generate_src.py')
    else:
        path.write_text(result)
