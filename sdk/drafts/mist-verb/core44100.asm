        move x:(r7+$86),b0
        asl #$2,b,b
        add b,a
        move a,x:(r7+$81)
        move #>$ffffff,m5
        rts
; Explicit half-away-from-zero rounding (not DSP convergent RND).
; Preserve wide rounded endpoints; saturation happens only after blending.
src_round_q23:
        tst a
        bpl src_round_positive
        clr b
        move #>$7fffff,b0
        bra src_round_addend
src_round_positive:
        clr b
        move #>$800000,b0
src_round_addend:
        add b,a
; Record endpoint overflow rather than silently claiming parity.
        move a,x0
        move a1,y0
        move x0,b
        cmp y0,b
        beq src_round_inrange
        move x:(r7+$85),b
        add #>$1,b
        move b1,x:(r7+$85)
src_round_inrange:
        move #>$0,a0
        rts

src_mix_output:
        move x:(r6+$5),b
        and #>$7f0000,b
        move b1,b
        tst b
        bne src_mix_nonzero
        move y0,a
        rts
src_mix_nonzero:
        cmp #>$7f0000,b
        beq src_mix_done
        move b1,y1
        move a1,x0
        mpy x0,y1,a
        move y0,x0
        mac -x0,y1,a
        add x0,a
src_mix_done:
        rts
